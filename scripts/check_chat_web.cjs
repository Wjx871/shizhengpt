// End-to-end check against the real model service. No mocked model responses.
const {chromium}=require(process.env.PLAYWRIGHT_PATH || 'playwright');
const fs=require('fs');
const path=require('path');
(async()=>{
 const root=path.resolve(__dirname,'..');
 const output=path.join(root,'evaluation','web');fs.mkdirSync(output,{recursive:true});
 const browser=await chromium.launch({headless:true});
 const page=await browser.newPage({viewport:{width:1280,height:900}});
 const errors=[];page.on('pageerror',e=>errors.push(e.message));
 await page.goto('http://127.0.0.1:7860');
 await page.getByText('模型已连接').waitFor();
 await page.screenshot({path:path.join(output,'chat-empty.png')});
 await page.getByLabel('消息',{exact:true}).fill('我的测试编号是松竹42。请只回答：已记住。');
 await page.getByRole('button',{name:'发送消息'}).click();
 await page.locator('.assistant .meta').waitFor({timeout:180000});
 const first=await page.locator('.assistant .bubble').innerText();
 await page.getByLabel('消息',{exact:true}).fill('我刚才的测试编号是什么？请只回答编号。');
 await page.getByRole('button',{name:'发送消息'}).click();
 await page.locator('.assistant .meta').nth(1).waitFor({timeout:180000});
 const history=await page.locator('.assistant .bubble').nth(1).innerText();
 if(!history.includes('松竹42'))throw Error('History recall check failed: '+history);
 await page.getByRole('button',{name:'新对话'}).click();
 if(await page.locator('.row').count())throw Error('New chat failed');
 await page.locator('#file').setInputFiles(path.join(root,'evaluation','images','tongue','3912.jpg'));
 await page.locator('#preview img').waitFor({state:'visible'});
 await page.getByRole('button',{name:'发送消息'}).click();
 await page.locator('.assistant .meta').waitFor({timeout:180000});
 const imageOnly=await page.locator('.assistant .bubble').innerText();
 if(await page.locator('.user .bubble img').count()!==1)throw Error('Image missing from conversation');
 await page.screenshot({path:path.join(output,'chat-image.png')});
 await page.locator('#file').setInputFiles(path.join(root,'evaluation','images','tongue','3912.jpg'));
 await page.getByLabel('消息',{exact:true}).fill('请仅描述图片中舌头的可见颜色，回答一句话。');
 await page.getByRole('button',{name:'发送消息'}).click();
 await page.locator('.assistant .meta').nth(1).waitFor({timeout:180000});
 const joint=await page.locator('.assistant .bubble').nth(1).innerText();
 await page.screenshot({path:path.join(output,'chat-conversation.png')});
 await page.setViewportSize({width:390,height:844});
 await page.screenshot({path:path.join(output,'chat-mobile.png')});
 const overflow=await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth);
 if(overflow||errors.length)throw Error(JSON.stringify({overflow,errors}));
 fs.writeFileSync(path.join(output,'checks.json'),JSON.stringify({first,history,imageOnly,joint,errors,mobileOverflow:overflow},null,2));
 console.log(JSON.stringify({ok:true,first,history,imageOnly,joint,errors,mobileOverflow:overflow}));
 await page.getByRole('button',{name:'新对话'}).click();
 await browser.close();
})().catch(e=>{console.error(e);process.exit(1)});
